package models;

public class Analytics {
    private int profileViews;
    private int searchImpressions;
    private int postImpressions;

    public int getProfileViews() {
        return profileViews;
    }

    public void setProfileViews(int profileViews) {
        this.profileViews = profileViews;
    }

    public int getSearchImpressions() {
        return searchImpressions;
    }

    public void setSearchImpressions(int searchImpressions) {
        this.searchImpressions = searchImpressions;
    }

    public int getPostImpressions() {
        return postImpressions;
    }

    public void setPostImpressions(int postImpressions) {
        this.postImpressions = postImpressions;
    }
}
